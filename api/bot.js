export default async function handler(req, res) {
  // Нам подходят только POST запросы от Telegram
  if (req.method !== 'POST') {
    return res.status(200).send('Бот Капитана яхты Grey работает!');
  }

  try {
    const { message } = req.body;

    if (!message || !message.text) {
      return res.status(200).send('No text message');
    }

    const chatId = message.chat.id;
    const userText = message.text;

    // Если пользователь нажал /start
    if (userText === '/start') {
      const welcomeMessage = "Приветствую на борту моторной яхты «Grey»! 🎣⚓\nЯ — Капитан вашего рыболовного тура в Кемере. Готовы выйти в открытое море за отличным уловом? Расскажите, вы один планируете или большой компанией?";
      await sendTelegram(chatId, welcomeMessage);
      return res.status(200).send('OK');
    }

    // Отправляем запрос Капитану (Gemini)
    try {
      const aiResponse = await model.generateContent(userText);
      const botReply = aiResponse.response.text() || "Штиль на связи... Повторите, пожалуйста, ваш вопрос, не расслышал.";
      await sendTelegram(chatId, botReply);
    } catch (aiError) {
      console.error('Ошибка Gemini:', aiError);
      await sendTelegram(chatId, "⏳ Извините, море слегка штормит (получил много сообщений). Пожалуйста, подождите пару секунд и повторите вопрос Капитану!");
    }

    return res.status(200).send('OK');

  } catch (error) {
    console.error('Общая ошибка:', error);
    return res.status(500).send('Internal Error');
  }
}

